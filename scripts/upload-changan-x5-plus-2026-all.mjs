// Native fetch only — no node_modules — avoids rxjs ETIMEDOUT
import { readFileSync, readdirSync } from "fs";
import { join, extname } from "path";

const envRaw = readFileSync("/Users/apple/Documents/voitures-chinoises-next/.env.local", "utf8");
const tokenLine = envRaw.split("\n").find(l => l.startsWith("SANITY_TOKEN"));
const TOKEN = tokenLine ? tokenLine.split("=").slice(1).join("=").replace(/^"|"$/g, "").trim() : "";
if (!TOKEN) { console.error("SANITY_TOKEN not found"); process.exit(1); }

const PROJECT_ID = "t3ow1rmc";
const DATASET    = "production";
const API        = `https://${PROJECT_ID}.api.sanity.io/v2024-01-01`;
const BASE_DIR   = "/Users/apple/Documents/Dossier photos voitures chinoises";

async function uploadPhoto(filePath, filename) {
  const ext = extname(filename).toLowerCase();
  const ct  = ext === ".png" ? "image/png" : "image/jpeg";
  const body = readFileSync(filePath);
  const res  = await fetch(`${API}/assets/images/${DATASET}`, {
    method: "POST",
    headers: { "Authorization": `Bearer ${TOKEN}`, "Content-Type": ct, "Content-Disposition": `attachment; filename="${filename}"` },
    body,
  });
  if (!res.ok) throw new Error(`Upload failed ${res.status}: ${await res.text()}`);
  const data = await res.json();
  return data.document._id;
}

async function uploadPhotosFromDir(dir) {
  const files = readdirSync(dir)
    .filter(f => [".jpg", ".jpeg", ".png"].includes(extname(f).toLowerCase()))
    .sort();
  console.log(`  ${files.length} photos from ${dir.split("/").pop()}`);
  const photos = [];
  for (const file of files) {
    const assetId = await uploadPhoto(join(dir, file), file);
    photos.push({ _type: "image", _key: assetId.slice(-8), asset: { _type: "reference", _ref: assetId } });
    console.log(`    ✓ ${file}`);
  }
  return photos;
}

async function mutate(mutations) {
  const res = await fetch(`${API}/data/mutate/${DATASET}`, {
    method: "POST",
    headers: { "Authorization": `Bearer ${TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify({ mutations }),
  });
  if (!res.ok) throw new Error(`Mutate failed ${res.status}: ${await res.text()}`);
  return res.json();
}

